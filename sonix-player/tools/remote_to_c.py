#!/usr/bin/env python3
"""Embeds web/remote.html in a C string for the browser remote server.

The page is one file with no subresources, so the server needs nothing but this
header. Run from anywhere; paths are relative to the repository root.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "web", "remote.html")
OUT = os.path.join(ROOT, "src", "system", "net", "remote_page.h")


def c_string(data):
    """One C string literal per source line, escaped for a C compiler."""
    lines = []
    for raw in data.split(b"\n"):
        parts = []
        for byte in raw:
            if byte == ord(b"\\"):
                parts.append("\\\\")
            elif byte == ord(b'"'):
                parts.append('\\"')
            elif 32 <= byte < 127:
                parts.append(chr(byte))
            else:
                # Octal, not hex: a hex escape would greedily absorb the next
                # character when it happens to be a hex digit.
                parts.append("\\%03o" % byte)
        lines.append('"' + "".join(parts) + '\\n"')
    # The last source line has no trailing newline in the split above.
    if lines:
        lines[-1] = lines[-1][:-3] + '"'
    return "\n\t".join(lines)


def main():
    with open(SOURCE, "rb") as f:
        data = f.read()
    header = (
        "// Generated by tools/remote_to_c.py -- do not edit.\n"
        "// The browser remote control page, carried in the binary.\n"
        "\n"
        "#ifndef BROWSERREMOTE_PAGE_H\n"
        "#define BROWSERREMOTE_PAGE_H\n"
        "\n"
        "static const char BROWSERREMOTE_PAGE[] =\n\t"
        + c_string(data)
        + ";\n"
        "\n"
        "#endif /* BROWSERREMOTE_PAGE_H */\n"
    )
    with open(OUT, "w", encoding="ascii") as f:
        f.write(header)
    print("wrote %s (%d bytes of HTML)" % (OUT, len(data)))


if __name__ == "__main__":
    main()
